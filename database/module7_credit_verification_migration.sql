-- Additive credit-verification metadata for LoanFlow.
-- No existing data, tables, columns, or relationships are removed.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOANFLOW_CREDIT_PROFILE' AND column_name='SCORE_SOURCE';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOANFLOW_CREDIT_PROFILE ADD (SCORE_SOURCE VARCHAR2(80))'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOANFLOW_CREDIT_PROFILE' AND column_name='REPORT_DATE';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOANFLOW_CREDIT_PROFILE ADD (REPORT_DATE DATE)'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOANFLOW_CREDIT_PROFILE' AND column_name='VERIFICATION_STATUS';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOANFLOW_CREDIT_PROFILE ADD (VERIFICATION_STATUS VARCHAR2(30) DEFAULT ''NOT_VERIFIED'' NOT NULL)'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOANFLOW_CREDIT_PROFILE' AND column_name='VERIFICATION_NOTES';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOANFLOW_CREDIT_PROFILE ADD (VERIFICATION_NOTES VARCHAR2(1000))'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOANFLOW_CREDIT_PROFILE' AND column_name='VERIFIED_BY';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOANFLOW_CREDIT_PROFILE ADD (VERIFIED_BY NUMBER)'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOANFLOW_CREDIT_PROFILE' AND column_name='VERIFIED_AT';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOANFLOW_CREDIT_PROFILE ADD (VERIFIED_AT DATE)'; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_CREDIT_VERIFICATION_HISTORY (
            VERIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            CUSTOMER_ID NUMBER NOT NULL,
            CREDIT_SCORE NUMBER(4),
            SCORE_SOURCE VARCHAR2(80),
            REPORT_DATE DATE,
            VERIFICATION_STATUS VARCHAR2(30) NOT NULL,
            VERIFICATION_NOTES VARCHAR2(1000),
            VERIFIED_BY NUMBER,
            VERIFIED_AT DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT FK_LF_CV_HISTORY_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES LMS_CUSTOMER(CUSTOMER_ID),
            CONSTRAINT FK_LF_CV_HISTORY_ADMIN FOREIGN KEY (VERIFIED_BY) REFERENCES USERS(USER_ID),
            CONSTRAINT CK_LF_CV_HISTORY_SCORE CHECK (CREDIT_SCORE IS NULL OR (CREDIT_SCORE BETWEEN 300 AND 900))
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

UPDATE LOANFLOW_CREDIT_PROFILE
SET VERIFICATION_STATUS = CASE
    WHEN ACADEMIC_CREDIT_SCORE IS NULL THEN 'NOT_VERIFIED'
    ELSE 'PENDING_REVIEW'
END
WHERE VERIFICATION_STATUS = 'NOT_VERIFIED';

COMMIT;
