-- EMI tracker: one immutable installment row per loan/month and an optional
-- installment reference on a successful payment. Safe to run more than once.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tables WHERE table_name = 'LOAN_EMI_SCHEDULE';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE '
            CREATE TABLE LOAN_EMI_SCHEDULE (
                INSTALLMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                LOAN_ID NUMBER NOT NULL,
                INSTALLMENT_NO NUMBER(5) NOT NULL,
                DUE_DATE DATE NOT NULL,
                DUE_AMOUNT NUMBER(15,2) NOT NULL,
                CONSTRAINT FK_EMI_SCHEDULE_LOAN FOREIGN KEY (LOAN_ID) REFERENCES LOAN(LOAN_ID),
                CONSTRAINT UX_EMI_SCHEDULE_LOAN_NO UNIQUE (LOAN_ID, INSTALLMENT_NO),
                CONSTRAINT CK_EMI_SCHEDULE_AMOUNT CHECK (DUE_AMOUNT > 0)
            )';
    END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='PAYMENT' AND column_name='INSTALLMENT_ID';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PAYMENT ADD (INSTALLMENT_ID NUMBER)';
    END IF;
    SELECT COUNT(*) INTO v_count FROM user_constraints WHERE constraint_name='FK_PAYMENT_INSTALLMENT';
    IF v_count = 0 THEN
        EXECUTE IMMEDIATE 'ALTER TABLE PAYMENT ADD CONSTRAINT FK_PAYMENT_INSTALLMENT FOREIGN KEY (INSTALLMENT_ID) REFERENCES LOAN_EMI_SCHEDULE(INSTALLMENT_ID)';
    END IF;
END;
/

-- Backfill schedule rows for all existing loans. The unique key makes this
-- idempotent and prevents duplicate installments.
INSERT INTO LOAN_EMI_SCHEDULE (LOAN_ID, INSTALLMENT_NO, DUE_DATE, DUE_AMOUNT)
SELECT l.LOAN_ID, levels.INSTALLMENT_NO,
       ADD_MONTHS(TRUNC(l.START_DATE), levels.INSTALLMENT_NO - 1),
       ROUND(l.EMI_AMOUNT, 2)
FROM LOAN l
JOIN (SELECT LEVEL INSTALLMENT_NO FROM dual CONNECT BY LEVEL <= 600) levels
  ON levels.INSTALLMENT_NO <= l.TENURE_MONTHS
WHERE NOT EXISTS (
    SELECT 1 FROM LOAN_EMI_SCHEDULE s
    WHERE s.LOAN_ID=l.LOAN_ID AND s.INSTALLMENT_NO=levels.INSTALLMENT_NO
);
COMMIT;
