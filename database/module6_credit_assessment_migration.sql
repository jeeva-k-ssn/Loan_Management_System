-- Additive academic credit-assessment storage for LoanFlow.
-- No existing table, column, relationship, or record is removed.
DECLARE
    v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LMS_CUSTOMER' AND column_name='MONTHLY_INCOME';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LMS_CUSTOMER ADD (MONTHLY_INCOME NUMBER(15,2))'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LMS_CUSTOMER' AND column_name='ACADEMIC_CREDIT_SCORE';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LMS_CUSTOMER ADD (ACADEMIC_CREDIT_SCORE NUMBER(4))'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LMS_CUSTOMER' AND column_name='CREDIT_HISTORY_STATUS';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LMS_CUSTOMER ADD (CREDIT_HISTORY_STATUS VARCHAR2(80))'; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_CREDIT_PROFILE (
            CUSTOMER_ID NUMBER PRIMARY KEY,
            MONTHLY_INCOME NUMBER(15,2),
            ACADEMIC_CREDIT_SCORE NUMBER(4),
            CREDIT_HISTORY_STATUS VARCHAR2(80),
            UPDATED_AT DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT FK_LF_CREDIT_PROFILE_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES LMS_CUSTOMER(CUSTOMER_ID),
            CONSTRAINT CK_LF_CREDIT_SCORE CHECK (ACADEMIC_CREDIT_SCORE IS NULL OR (ACADEMIC_CREDIT_SCORE BETWEEN 300 AND 900))
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_CREDIT_ASSESSMENT (
            ASSESSMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            APPLICATION_ID NUMBER NOT NULL,
            CREDIT_SCORE NUMBER(4),
            MONTHLY_INCOME NUMBER(15,2),
            EXISTING_EMI NUMBER(15,2) NOT NULL,
            NEW_EMI NUMBER(15,2) NOT NULL,
            TOTAL_EMI NUMBER(15,2) NOT NULL,
            EMI_INCOME_RATIO NUMBER(8,2),
            OUTSTANDING_DEBT NUMBER(15,2) NOT NULL,
            ELIGIBILITY VARCHAR2(20) NOT NULL,
            RISK_LEVEL VARCHAR2(20) NOT NULL,
            CREDIT_HISTORY VARCHAR2(80) NOT NULL,
            REASON VARCHAR2(1000) NOT NULL,
            ASSESSED_AT DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT UQ_LF_CREDIT_ASSESSMENT_APP UNIQUE (APPLICATION_ID),
            CONSTRAINT FK_LF_CREDIT_ASSESSMENT_APP FOREIGN KEY (APPLICATION_ID) REFERENCES LOAN_APPLICATION(APPLICATION_ID)
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- Copy any existing customer profile values into the dedicated profile table.
MERGE INTO LOANFLOW_CREDIT_PROFILE target
USING (SELECT CUSTOMER_ID, MONTHLY_INCOME, ACADEMIC_CREDIT_SCORE, CREDIT_HISTORY_STATUS FROM LMS_CUSTOMER) source
ON (target.CUSTOMER_ID=source.CUSTOMER_ID)
WHEN MATCHED THEN UPDATE SET MONTHLY_INCOME=source.MONTHLY_INCOME, ACADEMIC_CREDIT_SCORE=source.ACADEMIC_CREDIT_SCORE, CREDIT_HISTORY_STATUS=source.CREDIT_HISTORY_STATUS, UPDATED_AT=SYSDATE
WHEN NOT MATCHED THEN INSERT (CUSTOMER_ID,MONTHLY_INCOME,ACADEMIC_CREDIT_SCORE,CREDIT_HISTORY_STATUS) VALUES (source.CUSTOMER_ID,source.MONTHLY_INCOME,source.ACADEMIC_CREDIT_SCORE,source.CREDIT_HISTORY_STATUS);

COMMIT;
