-- Additive customer credit-report upload metadata.
-- Report files are stored outside Oracle; this table stores protected metadata only.
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_CREDIT_REPORT (
            REPORT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            CUSTOMER_ID NUMBER NOT NULL,
            FILE_NAME VARCHAR2(255) NOT NULL,
            STORAGE_PATH VARCHAR2(1000) NOT NULL,
            FILE_SIZE_BYTES NUMBER(15) NOT NULL,
            UPLOADED_AT DATE DEFAULT SYSDATE NOT NULL,
            REPORT_STATUS VARCHAR2(30) DEFAULT ''PENDING_REVIEW'' NOT NULL,
            CREDIT_SCORE NUMBER(4),
            VERIFIED_BY NUMBER,
            VERIFIED_AT DATE,
            NOTES VARCHAR2(1000),
            CONSTRAINT FK_LF_REPORT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES LMS_CUSTOMER(CUSTOMER_ID),
            CONSTRAINT FK_LF_REPORT_ADMIN FOREIGN KEY (VERIFIED_BY) REFERENCES USERS(USER_ID),
            CONSTRAINT CK_LF_REPORT_STATUS CHECK (REPORT_STATUS IN (''PENDING_REVIEW'',''VERIFIED'',''REJECTED'')),
            CONSTRAINT CK_LF_REPORT_SCORE CHECK (CREDIT_SCORE IS NULL OR (CREDIT_SCORE BETWEEN 300 AND 900))
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE 'CREATE INDEX IX_LF_REPORT_CUSTOMER ON LOANFLOW_CREDIT_REPORT(CUSTOMER_ID, UPLOADED_AT)';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
COMMIT;
