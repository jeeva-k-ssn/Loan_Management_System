-- Additive notification storage for LoanFlow.
-- Run once as the schema owner after the existing migrations.
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_NOTIFICATION (
            NOTIFICATION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            USER_ID NUMBER NOT NULL,
            TITLE VARCHAR2(120) NOT NULL,
            MESSAGE VARCHAR2(1000) NOT NULL,
            NOTIFICATION_TYPE VARCHAR2(40) NOT NULL,
            RELATED_ID NUMBER,
            IS_READ CHAR(1) DEFAULT ''N'' NOT NULL,
            CREATED_AT DATE DEFAULT SYSDATE NOT NULL,
            CONSTRAINT FK_LF_NOTIFICATION_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID),
            CONSTRAINT CK_LF_NOTIFICATION_READ CHECK (IS_READ IN (''Y'', ''N''))
        )';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
COMMIT;