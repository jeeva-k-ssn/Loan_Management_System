-- Additive simulated credit-bureau data. Existing upload/report records are preserved.
-- This table is the mock external bureau's stable source; LoanFlow never calculates CIBIL scores.
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_MOCK_CREDIT_REPORT (
            REPORT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            CUSTOMER_ID NUMBER NOT NULL,
            CIBIL_SCORE NUMBER(4) NOT NULL,
            ACTIVE_ACCOUNTS NUMBER(5) DEFAULT 0 NOT NULL,
            PAYMENT_HISTORY NUMBER(5,2) DEFAULT 0 NOT NULL,
            CREDIT_UTILIZATION NUMBER(5,2) DEFAULT 0 NOT NULL,
            RECENT_ENQUIRIES NUMBER(5) DEFAULT 0 NOT NULL,
            DEFAULTS NUMBER(5) DEFAULT 0 NOT NULL,
            TOTAL_OUTSTANDING NUMBER(15,2) DEFAULT 0 NOT NULL,
            RETRIEVED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            SOURCE VARCHAR2(100) DEFAULT ''TransUnion CIBIL (SIMULATED)'' NOT NULL,
            CONSTRAINT UQ_LF_MOCK_REPORT_CUSTOMER UNIQUE (CUSTOMER_ID),
            CONSTRAINT FK_LF_MOCK_REPORT_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES LMS_CUSTOMER(CUSTOMER_ID),
            CONSTRAINT CK_LF_MOCK_REPORT_SCORE CHECK (CIBIL_SCORE BETWEEN 300 AND 900),
            CONSTRAINT CK_LF_MOCK_REPORT_PERCENT CHECK (PAYMENT_HISTORY BETWEEN 0 AND 100 AND CREDIT_UTILIZATION BETWEEN 0 AND 100)
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

DECLARE v_count NUMBER;
BEGIN
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOAN_APPLICATION' AND column_name='CREDIT_CONSENT_GIVEN';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOAN_APPLICATION ADD (CREDIT_CONSENT_GIVEN CHAR(1) DEFAULT ''N'' NOT NULL)'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LOAN_APPLICATION' AND column_name='CREDIT_CONSENT_AT';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LOAN_APPLICATION ADD (CREDIT_CONSENT_AT TIMESTAMP)'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LMS_CUSTOMER' AND column_name='PAN_NUMBER';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LMS_CUSTOMER ADD (PAN_NUMBER VARCHAR2(10))'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LMS_CUSTOMER' AND column_name='IDENTITY_TYPE';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LMS_CUSTOMER ADD (IDENTITY_TYPE VARCHAR2(30))'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LMS_CUSTOMER' AND column_name='IDENTITY_NUMBER';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LMS_CUSTOMER ADD (IDENTITY_NUMBER VARCHAR2(40))'; END IF;
    SELECT COUNT(*) INTO v_count FROM user_tab_columns WHERE table_name='LMS_CUSTOMER' AND column_name='EMPLOYMENT_STATUS';
    IF v_count=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE LMS_CUSTOMER ADD (EMPLOYMENT_STATUS VARCHAR2(80))'; END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_CREDIT_RETRIEVAL (
            RETRIEVAL_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            APPLICATION_ID NUMBER NOT NULL,
            CUSTOMER_ID NUMBER NOT NULL,
            CIBIL_SCORE NUMBER(4) NOT NULL,
            ACTIVE_ACCOUNTS NUMBER(5) NOT NULL,
            PAYMENT_HISTORY NUMBER(5,2) NOT NULL,
            CREDIT_UTILIZATION NUMBER(5,2) NOT NULL,
            RECENT_ENQUIRIES NUMBER(5) NOT NULL,
            DEFAULTS NUMBER(5) NOT NULL,
            TOTAL_OUTSTANDING NUMBER(15,2) NOT NULL,
            SOURCE VARCHAR2(100) NOT NULL,
            RETRIEVED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            RETRIEVED_BY NUMBER,
            CONSTRAINT UQ_LF_CREDIT_RETRIEVAL_APP UNIQUE (APPLICATION_ID),
            CONSTRAINT FK_LF_RETRIEVAL_APP FOREIGN KEY (APPLICATION_ID) REFERENCES LOAN_APPLICATION(APPLICATION_ID),
            CONSTRAINT FK_LF_RETRIEVAL_CUSTOMER FOREIGN KEY (CUSTOMER_ID) REFERENCES LMS_CUSTOMER(CUSTOMER_ID),
            CONSTRAINT FK_LF_RETRIEVAL_OFFICER FOREIGN KEY (RETRIEVED_BY) REFERENCES USERS(USER_ID)
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/

-- Seed stable simulated reports for existing customers without changing existing records.
MERGE INTO LOANFLOW_MOCK_CREDIT_REPORT t
USING (SELECT CUSTOMER_ID FROM LMS_CUSTOMER) s ON (t.CUSTOMER_ID=s.CUSTOMER_ID)
WHEN NOT MATCHED THEN INSERT (CUSTOMER_ID,CIBIL_SCORE,ACTIVE_ACCOUNTS,PAYMENT_HISTORY,CREDIT_UTILIZATION,RECENT_ENQUIRIES,DEFAULTS,TOTAL_OUTSTANDING)
VALUES (s.CUSTOMER_ID,782,2,96,31,1,0,185000);
COMMIT;

