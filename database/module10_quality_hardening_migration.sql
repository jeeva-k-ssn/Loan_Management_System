-- Additive audit trail for officer/admin actions. Existing records are untouched.
BEGIN
    EXECUTE IMMEDIATE '
        CREATE TABLE LOANFLOW_AUDIT_LOG (
            AUDIT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            USER_ID NUMBER NOT NULL,
            ACTION VARCHAR2(40) NOT NULL,
            ENTITY_TYPE VARCHAR2(40) NOT NULL,
            ENTITY_ID NUMBER NOT NULL,
            DETAILS VARCHAR2(1000),
            CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
            CONSTRAINT FK_LF_AUDIT_USER FOREIGN KEY (USER_ID) REFERENCES USERS(USER_ID)
        )';
EXCEPTION WHEN OTHERS THEN IF SQLCODE != -955 THEN RAISE; END IF;
END;
/
COMMIT;

-- Give the first three existing customers distinct, deterministic demonstration profiles.
-- No rows are deleted and no score is calculated by LoanFlow.
MERGE INTO LOANFLOW_MOCK_CREDIT_REPORT t
USING (SELECT CUSTOMER_ID, ROW_NUMBER() OVER (ORDER BY CUSTOMER_ID) AS SCENARIO_NO FROM LMS_CUSTOMER) s
ON (t.CUSTOMER_ID=s.CUSTOMER_ID)
WHEN MATCHED THEN UPDATE SET
    CIBIL_SCORE=CASE s.SCENARIO_NO WHEN 1 THEN 782 WHEN 2 THEN 691 ELSE 590 END,
    ACTIVE_ACCOUNTS=CASE s.SCENARIO_NO WHEN 1 THEN 2 WHEN 2 THEN 3 ELSE 4 END,
    PAYMENT_HISTORY=CASE s.SCENARIO_NO WHEN 1 THEN 96 WHEN 2 THEN 87 ELSE 62 END,
    CREDIT_UTILIZATION=CASE s.SCENARIO_NO WHEN 1 THEN 31 WHEN 2 THEN 52 ELSE 88 END,
    RECENT_ENQUIRIES=CASE s.SCENARIO_NO WHEN 1 THEN 1 WHEN 2 THEN 3 ELSE 6 END,
    DEFAULTS=CASE s.SCENARIO_NO WHEN 1 THEN 0 WHEN 2 THEN 0 ELSE 2 END,
    TOTAL_OUTSTANDING=CASE s.SCENARIO_NO WHEN 1 THEN 185000 WHEN 2 THEN 320000 ELSE 610000 END,
    SOURCE='TransUnion CIBIL (SIMULATED)', RETRIEVED_AT=SYSTIMESTAMP
WHEN NOT MATCHED THEN INSERT
    (CUSTOMER_ID,CIBIL_SCORE,ACTIVE_ACCOUNTS,PAYMENT_HISTORY,CREDIT_UTILIZATION,RECENT_ENQUIRIES,DEFAULTS,TOTAL_OUTSTANDING)
    VALUES (s.CUSTOMER_ID,CASE s.SCENARIO_NO WHEN 1 THEN 782 WHEN 2 THEN 691 ELSE 590 END,
            CASE s.SCENARIO_NO WHEN 1 THEN 2 WHEN 2 THEN 3 ELSE 4 END,
            CASE s.SCENARIO_NO WHEN 1 THEN 96 WHEN 2 THEN 87 ELSE 62 END,
            CASE s.SCENARIO_NO WHEN 1 THEN 31 WHEN 2 THEN 52 ELSE 88 END,
            CASE s.SCENARIO_NO WHEN 1 THEN 1 WHEN 2 THEN 3 ELSE 6 END,
            CASE s.SCENARIO_NO WHEN 1 THEN 0 WHEN 2 THEN 0 ELSE 2 END,
            CASE s.SCENARIO_NO WHEN 1 THEN 185000 WHEN 2 THEN 320000 ELSE 610000 END);
COMMIT;
